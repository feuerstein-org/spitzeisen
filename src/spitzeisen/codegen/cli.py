"""The unified ``spitzeisen-gen`` build command."""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import tempfile
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Any

import click
import yaml
from pydantic import ValidationError

from spitzeisen.codegen.diagnostics import CodegenError, SourceLocation, error
from spitzeisen.codegen.document import OpenAPIDocument
from spitzeisen.codegen.generate import (
    GeneratedModule,
    format_python,
    generate_plan,
    generated_model_names,
    model_exports_module,
    prune_spec,
)
from spitzeisen.codegen.lower import lower_document
from spitzeisen.codegen.manifest import Manifest
from spitzeisen.codegen.policy import ClientPlan, compile_manifest

if TYPE_CHECKING:
    from collections.abc import Generator

DEFAULT_SPEC_DIR = Path("spec")
DEFAULT_MODEL_BASE_CLASS = "spitzeisen.SpitzeisenModel"
MODEL_HEADER = re.compile(
    r"\A# generated by datamodel-codegen:\r?\n#\s+filename:\s+(?P<filename>[^\r\n]+)\r?\n",
)
_SPEC_FILENAMES = ("vendor.yaml", "vendor.yml", "vendor.json", "openapi.yaml", "openapi.yml", "openapi.json")


@dataclass(frozen=True, slots=True)
class BuildInputs:
    """Validated source inputs and their compiled SDK plan."""

    manifest: Manifest
    spec: dict[str, Any] | None
    client: ClientPlan


def load_manifest(path: Path) -> Manifest:
    """Load and validate a generation manifest."""
    location = SourceLocation(path.resolve().as_uri())
    try:
        data = yaml.safe_load(path.read_text())
        return Manifest.model_validate(data)
    except OSError as exc:
        code = "manifest.read"
        raise error(code, str(exc), location) from exc
    except yaml.YAMLError as exc:
        code = "manifest.syntax"
        raise error(code, str(exc), location) from exc
    except ValidationError as exc:
        code = "manifest.invalid"
        raise error(code, str(exc), location) from exc


def apply_overlay(spec: Path, overlay: Path, output: Path) -> None:
    """Apply an OpenAPI Overlay without making the patched document a source of truth."""
    subprocess.run(  # noqa: S603
        ["oas-patch", "overlay", str(spec), str(overlay), "-o", str(output)],  # noqa: S607
        check=True,
        capture_output=True,
        text=True,
    )


def write(modules: list[GeneratedModule]) -> set[Path]:
    """Atomically replace generated modules and preserve existing public scaffolds."""
    written: set[Path] = set()
    for module in modules:
        if module.create_once and module.path.exists():
            continue
        module.path.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=module.path.parent,
            prefix=f".{module.path.name}.",
            suffix=".tmp",
            delete=False,
        ) as temporary:
            temporary.write(module.source)
            temporary_path = Path(temporary.name)
        try:
            temporary_path.replace(module.path)
        finally:
            temporary_path.unlink(missing_ok=True)
        written.add(module.path)
    return written


def is_current(module: GeneratedModule) -> bool:
    """Whether generated output is current or a public scaffold exists."""
    if not module.path.exists():
        return False
    return module.create_once or module.path.read_text() == module.source


def normalize_model_header(source: str) -> str:
    """Replace datamodel-code-generator's temporary filename with stable provenance."""
    match = MODEL_HEADER.match(source)
    if match is None:
        return source
    return f"# Generated by datamodel-code-generator from selected OpenAPI operations.\n{source[match.end() :]}"


@click.group()
def main() -> None:
    """Compile an OpenAPI document and SDK manifest into a polished Python client."""


# TODO: Is it a good idea to have a default spec dir? Also add "help" line
@main.command("generate")
@click.option("--spec-dir", type=click.Path(path_type=Path), default=DEFAULT_SPEC_DIR, show_default=True)
@click.option("--package-root", type=click.Path(path_type=Path), required=True, help="The client package directory.")
@click.option("--base-class", default=DEFAULT_MODEL_BASE_CLASS, show_default=True)
def generate_command(spec_dir: Path, package_root: Path, base_class: str) -> None:
    """Generate models, endpoint APIs, and aggregate async/sync clients in one pass."""
    try:
        modules = _render(spec_dir, package_root, base_class)
    except (CodegenError, subprocess.CalledProcessError) as exc:
        raise click.ClickException(_failure_message(exc)) from exc
    written = write(modules)
    stale_generated = _orphaned_generated_modules(package_root, modules)
    for path in stale_generated:
        path.unlink()
    for module in modules:
        action = "preserved" if module.create_once and module.path not in written else "wrote"
        click.echo(f"  {action}: {module.path}")
    for path in stale_generated:
        click.echo(f"  removed stale generated module: {path}")
    click.echo(f"generated {len(written)} files; preserved {len(modules) - len(written)} public extensions")


@main.command()
@click.option("--spec-dir", type=click.Path(path_type=Path), default=DEFAULT_SPEC_DIR, show_default=True)
@click.option("--package-root", type=click.Path(path_type=Path), required=True, help="The client package directory.")
@click.option("--base-class", default=DEFAULT_MODEL_BASE_CLASS, show_default=True)
def check(spec_dir: Path, package_root: Path, base_class: str) -> None:
    """Fail when committed generated output differs from a clean compilation."""
    try:
        modules = _render(spec_dir, package_root, base_class)
    except (CodegenError, subprocess.CalledProcessError) as exc:
        raise click.ClickException(_failure_message(exc)) from exc
    stale = [module.path for module in modules if not is_current(module)]
    stale.extend(_orphaned_generated_modules(package_root, modules))
    if stale:
        click.echo("generated code is stale; run `spitzeisen-gen generate`:", err=True)
        for path in stale:
            click.echo(f"  {path}", err=True)
        sys.exit(1)
    click.echo(f"{len(modules)} generated or scaffolded modules are up to date")


def _render(spec_dir: Path, package_root: Path, base_class: str = DEFAULT_MODEL_BASE_CLASS) -> list[GeneratedModule]:
    """Compile all inputs and render the complete output tree."""
    inputs = _load_inputs(spec_dir)
    _validate_handwritten_models(inputs.client, package_root)
    modules = generate_plan(inputs.client, package_root)
    generated_endpoints = tuple(endpoint for endpoint in inputs.client.endpoints if endpoint.generate_model)
    if generated_endpoints:
        if inputs.spec is None:
            code = "models.spec-required"
            message = "at least one endpoint enables model generation, but no OpenAPI document was found"
            raise error(code, message, SourceLocation((spec_dir / "manifest.yaml").resolve().as_uri()))
        model_source = _generate_model_source(
            spec=inputs.spec,
            spec_dir=spec_dir,
            manifest=inputs.manifest,
            client=inputs.client,
            package_root=package_root,
            base_class=base_class,
        )
        generated_names = set(generated_model_names(model_source))
        missing_models = sorted(
            endpoint.model for endpoint in generated_endpoints if endpoint.model not in generated_names
        )
        if missing_models:
            code = "models.response-model"
            message = (
                f"the model backend did not generate response models {missing_models}; "
                "check response schema titles or set `generate_model: false`"
            )
            raise error(code, message, SourceLocation((spec_dir / "manifest.yaml").resolve().as_uri()))
        modules.append(GeneratedModule(package_root / "models" / "_generated.py", model_source))
        modules.append(model_exports_module(inputs.client, package_root, model_source))
    return modules


def _load_inputs(spec_dir: Path) -> BuildInputs:
    """Load the manifest and safely validate/lower an optional vendor document."""
    manifest = load_manifest(spec_dir / "manifest.yaml")
    source = _find_spec(spec_dir)
    if source is None:
        return BuildInputs(manifest=manifest, spec=None, client=compile_manifest(manifest, None))
    overlay = spec_dir / "overlay.yaml"
    if overlay.exists():
        with _temporary_sibling(source, suffix=".json") as patched:
            apply_overlay(source, overlay, patched)
            document = OpenAPIDocument.from_path(patched, reference_root=spec_dir)
            client = compile_manifest(manifest, lower_document(document))
            return BuildInputs(manifest=manifest, spec=dict(document.data), client=client)
    document = OpenAPIDocument.from_path(source, reference_root=spec_dir)
    return BuildInputs(
        manifest=manifest,
        spec=dict(document.data),
        client=compile_manifest(manifest, lower_document(document)),
    )


def _find_spec(spec_dir: Path) -> Path | None:
    """Find the conventional vendor/OpenAPI input without guessing outside the source directory."""
    matches = [spec_dir / name for name in _SPEC_FILENAMES if (spec_dir / name).exists()]
    if len(matches) > 1:
        code = "openapi.ambiguous-input"
        message = f"multiple OpenAPI inputs found: {[path.name for path in matches]}"
        raise error(code, message, SourceLocation(spec_dir.resolve().as_uri()))
    return matches[0] if matches else None


def _validate_handwritten_models(client: ClientPlan, package_root: Path) -> None:
    """Require explicitly handwritten response-model modules before generating their endpoints."""
    missing = [
        endpoint
        for endpoint in client.endpoints
        if not endpoint.generate_model and not (package_root / "models" / f"{endpoint.key}.py").exists()
    ]
    if not missing:
        return
    code = "models.handwritten-model"
    paths = [f"models/{endpoint.key}.py ({endpoint.model})" for endpoint in missing]
    message = f"generate_model=false requires handwritten model modules: {paths}"
    raise error(code, message, SourceLocation(package_root.resolve().as_uri()))


def _generate_model_source(
    *,
    spec: dict[str, Any],
    spec_dir: Path,
    manifest: Manifest,
    client: ClientPlan,
    package_root: Path,
    base_class: str,
) -> str:
    """Run the replaceable Pydantic model backend and return reproducible source."""
    extra: list[str] = []
    if aliases := manifest.model_aliases():
        extra += ["--aliases", json.dumps(aliases)]
    if overrides := manifest.model_type_overrides():
        extra += ["--type-overrides", json.dumps(overrides)]
    with _temporary_sibling(spec_dir / "openapi", suffix=".json") as model_input:
        model_input.write_text(json.dumps(prune_spec(spec, client), indent=2))
        with _temporary_sibling(package_root / "models" / "generated", suffix=".py") as output:
            subprocess.run(  # noqa: S603
                [  # noqa: S607
                    "datamodel-codegen",
                    "--input",
                    str(model_input),
                    "--input-file-type",
                    "openapi",
                    "--openapi-scopes",
                    "paths",
                    "--output",
                    str(output),
                    "--output-model-type",
                    "pydantic_v2.BaseModel",
                    "--use-title-as-name",
                    "--disable-timestamp",
                    "--strict-nullable",
                    "--enum-field-as-literal",
                    "all",
                    "--base-class",
                    base_class,
                    "--reuse-model",
                    "--use-annotated",
                    "--field-constraints",
                    "--use-union-operator",
                    "--use-standard-collections",
                    "--use-schema-description",
                    "--use-field-description",
                    "--formatters",
                    "ruff-format",
                    *extra,
                ],
                check=True,
                capture_output=True,
                text=True,
            )
            source = normalize_model_header(output.read_text())
    destination = package_root / "models" / "_generated.py"
    return format_python(source, str(destination))


@contextmanager
def _temporary_sibling(anchor: Path, *, suffix: str) -> Generator[Path]:
    """Yield a temporary path beside an input so relative references keep their meaning."""
    anchor.parent.mkdir(parents=True, exist_ok=True)
    descriptor, name = tempfile.mkstemp(dir=anchor.parent, prefix=".spitzeisen-", suffix=suffix)
    os.close(descriptor)
    path = Path(name)
    try:
        yield path
    finally:
        path.unlink(missing_ok=True)


def _orphaned_generated_modules(package_root: Path, modules: list[GeneratedModule]) -> list[Path]:
    """Find replaceable generated Python modules no longer present in the build plan."""
    expected = {module.path.resolve() for module in modules if not module.create_once}
    candidates: list[Path] = []
    for folder in (package_root / "_async" / "_generated", package_root / "_sync" / "_generated"):
        if folder.exists():
            candidates.extend(path for path in folder.glob("*.py") if path.name != "__init__.py")
    candidates.extend(
        path
        for path in (package_root / "models" / "_generated.py", package_root / "models" / "_exports.py")
        if path.exists()
    )
    return sorted(path for path in candidates if path.resolve() not in expected)


def _failure_message(exc: CodegenError | subprocess.CalledProcessError) -> str:
    """Render compiler or backend failures without exposing a Python traceback."""
    if isinstance(exc, CodegenError):
        return str(exc)
    detail = (exc.stderr or exc.stdout or str(exc)).strip()
    return f"model generation failed: {detail}"


if __name__ == "__main__":
    main()
