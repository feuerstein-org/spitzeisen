"""
`spitzeisen-gen` — the build-time CLI.

Three commands a client repo can wire into its task runner:

    spitzeisen-gen models     vendor spec + overlay -> pydantic models
    spitzeisen-gen endpoints  manifest (+ spec)     -> endpoint modules
    spitzeisen-gen check      manifest (+ spec)     -> verify committed generated modules

`check` is what CI runs. Regenerated bases are compared byte for byte; create-once public
extension modules only have to exist because they intentionally belong to the client package.
"""

import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

import click
import yaml

from spitzeisen.codegen.generate import (
    GeneratedModule,
    format_python,
    generate,
    model_exports_module,
    model_extension_modules,
    prune_spec,
)
from spitzeisen.codegen.manifest import Manifest

DEFAULT_SPEC_DIR = Path("spec")
DEFAULT_MODEL_BASE_CLASS = "spitzeisen.SpitzeisenModel"
MODEL_HEADER = re.compile(
    r"\A# generated by datamodel-codegen:\r?\n#\s+filename:\s+(?P<filename>[^\r\n]+)\r?\n",
)


def load_manifest(path: Path) -> Manifest:
    """Load and validate a manifest."""
    return Manifest.model_validate(yaml.safe_load(path.read_text()))


def load_spec(path: Path | None) -> dict[str, Any] | None:
    """Load an OpenAPI document, or None when the vendor publishes none."""
    if path is None or not path.exists():
        return None
    text = path.read_text()
    return json.loads(text) if path.suffix == ".json" else yaml.safe_load(text)


def apply_overlay(spec: Path, overlay: Path, output: Path) -> None:
    """Apply an OpenAPI Overlay, patching the vendor's document without forking it."""
    subprocess.run(  # noqa: S603
        ["oas-patch", "overlay", str(spec), str(overlay), "-o", str(output)],  # noqa: S607
        check=True,
        capture_output=True,
    )


def write(modules: list[GeneratedModule]) -> set[Path]:
    """Write regenerated modules and create public extension modules only when absent."""
    written: set[Path] = set()
    for module in modules:
        if module.create_once and module.path.exists():
            continue
        module.path.parent.mkdir(parents=True, exist_ok=True)
        module.path.write_text(module.source)
        written.add(module.path)
    return written


def is_current(module: GeneratedModule) -> bool:
    """Whether generated output is current or a create-once extension module exists."""
    if not module.path.exists():
        return False
    return module.create_once or module.path.read_text() == module.source


def normalize_model_header(source: str) -> str:
    """Turn datamodel-code-generator's machine-style header into a prose comment."""
    match = MODEL_HEADER.match(source)
    if match is None:
        return source
    filename = match.group("filename").strip()
    return f"# Generated by datamodel-code-generator from {filename}.\n{source[match.end() :]}"


@click.group()
def main() -> None:
    """Generate a spitzeisen client from an OpenAPI document and a manifest."""


@main.command()
@click.option("--spec-dir", type=click.Path(path_type=Path), default=DEFAULT_SPEC_DIR, show_default=True)
@click.option("--package-root", type=click.Path(path_type=Path), required=True, help="The client package directory.")
@click.option("--base-class", default=DEFAULT_MODEL_BASE_CLASS, show_default=True)
def models(spec_dir: Path, package_root: Path, base_class: str) -> None:
    """Generate schema storage, public exports, and response-model extensions."""
    patched = spec_dir / "patched.json"
    apply_overlay(spec_dir / "vendor.json", spec_dir / "overlay.yaml", patched)

    # Only the endpoints this client implements: see `prune_spec`.
    manifest = load_manifest(spec_dir / "manifest.yaml")
    pruned = spec_dir / "pruned.json"
    spec = load_spec(patched)
    assert spec is not None  # noqa: S101 - apply_overlay just wrote it
    pruned.write_text(json.dumps(prune_spec(spec, manifest), indent=1))

    # Field renames and custom field types are declared per endpoint in the manifest; the
    # types themselves live in the client library, so spitzeisen stays free of vendor quirks.
    extra: list[str] = []
    if aliases := manifest.model_aliases():
        extra += ["--aliases", json.dumps(aliases)]
    if overrides := manifest.model_type_overrides():
        extra += ["--type-overrides", json.dumps(overrides)]

    # TODO: Can't this be run as a library? Do we need subprocess?
    output = package_root / "models" / "_generated.py"
    output.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(  # noqa: S603
        [  # noqa: S607
            "datamodel-codegen",
            "--input",
            str(pruned),
            "--input-file-type",
            "openapi",
            # Responses only. The request-parameter models a spec implies are never used:
            # the endpoint template builds each signature from the manifest instead.
            "--openapi-scopes",
            "paths",
            "--output",
            str(output),
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--use-title-as-name",
            # Committed output must be reproducible: generation time is not model content.
            "--disable-timestamp",
            # Take `nullable` at its word: without this, a required field can never be
            # null and an optional one always can, which is not what a schema says.
            "--strict-nullable",
            # Literals, not Enum classes: a generated model hands callers plain strings,
            # which is what downstream dataframes and JSON round-trips expect.
            "--enum-field-as-literal",
            "all",
            "--base-class",
            base_class,
            "--reuse-model",
            "--use-annotated",
            "--field-constraints",
            "--use-union-operator",
            "--use-standard-collections",
            "--use-schema-description",
            "--use-field-description",
            "--formatters",
            "ruff-format",
            *extra,
        ],
        check=True,
    )
    # Through the same formatter as everything else, so imports are sorted the same way
    # and `check` compares like with like.
    model_source = format_python(normalize_model_header(output.read_text()), str(output))
    output.write_text(model_source)
    extensions = model_extension_modules(manifest, package_root)
    extensions.append(model_exports_module(manifest, package_root, model_source))
    written = write(extensions)
    click.echo(f"generated models -> {output}")
    for module in extensions:
        action = ("preserved" if module.path not in written else "created") if module.create_once else "wrote"
        click.echo(f"  {action}: {module.path}")


@main.command()
@click.option("--spec-dir", type=click.Path(path_type=Path), default=DEFAULT_SPEC_DIR, show_default=True)
@click.option("--package-root", type=click.Path(path_type=Path), required=True, help="The client package directory.")
def endpoints(spec_dir: Path, package_root: Path) -> None:
    """Generate endpoint modules from the manifest."""
    modules = _render(spec_dir, package_root)
    written = write(modules)
    for module in modules:
        action = "preserved" if module.create_once and module.path not in written else "wrote"
        click.echo(f"  {action}: {module.path}")


@main.command()
@click.option("--spec-dir", type=click.Path(path_type=Path), default=DEFAULT_SPEC_DIR, show_default=True)
@click.option("--package-root", type=click.Path(path_type=Path), required=True)
def check(spec_dir: Path, package_root: Path) -> None:
    """Fail if the committed generated tree differs from what would be generated now."""
    modules = _render(spec_dir, package_root)
    stale = [module.path for module in modules if not is_current(module)]
    if stale:
        click.echo("generated code is stale; run `spitzeisen-gen endpoints`:", err=True)
        for path in stale:
            click.echo(f"  {path}", err=True)
        sys.exit(1)
    click.echo(f"{len(modules)} generated or scaffolded modules are up to date")


def _render(spec_dir: Path, package_root: Path) -> list[GeneratedModule]:
    """Load inputs and render, applying the overlay first when a vendor spec is present."""
    manifest = load_manifest(spec_dir / "manifest.yaml")
    vendor = spec_dir / "vendor.json"
    spec = None
    if vendor.exists():
        patched = spec_dir / "patched.json"
        overlay = spec_dir / "overlay.yaml"
        if overlay.exists():
            apply_overlay(vendor, overlay, patched)
            spec = load_spec(patched)
        else:
            spec = load_spec(vendor)
    modules = generate(manifest, spec, package_root)
    model_source = package_root / "models" / "_generated.py"
    if model_source.exists():
        modules.append(model_exports_module(manifest, package_root, model_source.read_text()))
    return modules


if __name__ == "__main__":
    main()
